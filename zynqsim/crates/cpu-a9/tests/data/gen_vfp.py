#!/usr/bin/env python3
"""Assemble the ISA test programs and emit them as Rust constants.

Usage: gen_vfp.py <vfp_groups.s> <out.rs>

Each `@@NAME` group of the source is assembled on its own (labels stay local to it) with the
Xilinx GNU toolchain for armv7-a, and the words are read back from `objdump -d`. Every source
instruction must produce exactly one word; a mismatch stops the script. The tools directory
comes from the ARM_GCC_BIN environment variable, defaulting to the Vitis 2022.1 install.
"""
import os
import re
import subprocess
import sys
import tempfile

TOOLS = os.environ.get(
    "ARM_GCC_BIN",
    r"C:\Xilinx\Vitis\2022.1\gnu\aarch32\nt\gcc-arm-none-eabi\bin",
)
AS = os.path.join(TOOLS, "arm-none-eabi-as.exe")
OBJDUMP = os.path.join(TOOLS, "arm-none-eabi-objdump.exe")


def groups(path):
    """Yields (name, lines) for each `@@NAME` group."""
    cur = None
    body = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if line.startswith("@@"):
                if cur is not None:
                    yield cur, body
                cur = line[2:].strip()
                body = []
            elif line.strip():
                body.append(line.strip())
    if cur is not None:
        yield cur, body


def assemble(workdir, name, lines):
    src = os.path.join(workdir, f"grp_{name}.s")
    obj = os.path.join(workdir, f"grp_{name}.o")
    with open(src, "w", encoding="utf-8") as f:
        f.write("\t.syntax unified\n\t.arm\n")
        f.write("\n".join(lines) + "\n")
    subprocess.run([AS, "-march=armv8-a", "-mfpu=fp-armv8", "-o", obj, src], check=True)
    out = subprocess.run(
        [OBJDUMP, "-d", obj], check=True, capture_output=True, text=True
    ).stdout
    words = []
    for line in out.splitlines():
        m = re.match(r"^\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*\t", line)
        if m:
            words.append(int(m.group(2).split()[0], 16))
    return words


def is_instruction(line):
    # Labels end with ':'; everything else (including .word data) produces one word.
    return not line.endswith(":")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out_path = sys.argv[1], sys.argv[2]
    parts = []
    with tempfile.TemporaryDirectory() as workdir:
        for name, body in groups(src):
            insns = [line for line in body if is_instruction(line)]
            words = assemble(workdir, name, body)
            if len(words) != len(insns):
                sys.exit(f"{name}: {len(insns)} source lines but {len(words)} words")
            const = name if name.startswith("PROG_") else "PROG_" + name
            parts.append(f"/// `{name}`: assembled by the Xilinx GNU toolchain (objdump order).")
            parts.append(f"pub const {const}: &[u32] = &[")
            for src_line, w in zip(insns, words):
                parts.append(f"    0x{w:08x}, // {src_line}")
            parts.append("];")
            parts.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tests/data/gen_vfp.py from tests/data/vfp_groups.s. Do not edit.\n\n")
        f.write("\n".join(parts))
        f.write("\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
