#!/usr/bin/env python3
"""Assemble the Thumb test programs and emit them as Rust halfword arrays.

Usage: gen_thumb.py <thumb_groups.s> <out.rs>

Each `@@NAME` group is assembled on its own (labels stay local to it) in Thumb-2 mode for
armv7-a with the Xilinx GNU toolchain; the halfwords are read back from `objdump -d`, so every
16-bit instruction is one halfword and every 32-bit instruction is two (first halfword first).
The output is `&[u16]` (little-endian in memory when loaded). Every source instruction line must
produce exactly one disassembled instruction; a mismatch stops the script. The tools directory
comes from the ARM_GCC_BIN environment variable, defaulting to the Vitis 2022.1 install.

This runs at test-generation time only: the Rust tests use the committed output and need no
toolchain.
"""
import os
import re
import subprocess
import sys
import tempfile

TOOLS = os.environ.get(
    "ARM_GCC_BIN",
    r"C:\Xilinx\Vitis\2022.1\gnu\aarch32\nt\gcc-arm-none-eabi\bin",
)
AS = os.path.join(TOOLS, "arm-none-eabi-as.exe")
OBJDUMP = os.path.join(TOOLS, "arm-none-eabi-objdump.exe")


def groups(path):
    """Yields (name, lines) for each `@@NAME` group."""
    cur = None
    body = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if line.startswith("@@"):
                if cur is not None:
                    yield cur, body
                cur = line[2:].strip()
                body = []
            elif line.strip():
                body.append(line.strip())
    if cur is not None:
        yield cur, body


def is_instruction(line):
    # Labels end with ':'; everything else produces instructions.
    return not line.endswith(":") and not line.startswith(".")


def assemble(workdir, name, lines):
    src = os.path.join(workdir, f"grp_{name}.s")
    obj = os.path.join(workdir, f"grp_{name}.o")
    with open(src, "w", encoding="utf-8") as f:
        f.write("\t.syntax unified\n\t.thumb\n")
        f.write("\n".join(lines) + "\n")
    subprocess.run([AS, "-march=armv7-a", "-mthumb", "-o", obj, src], check=True)
    out = subprocess.run(
        [OBJDUMP, "-d", obj], check=True, capture_output=True, text=True
    ).stdout
    halfwords = []
    insns = 0
    for line in out.splitlines():
        m = re.match(r"^\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*\t", line)
        if m:
            insns += 1
            halfwords.extend(int(t, 16) for t in m.group(2).split())
    return halfwords, insns


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out_path = sys.argv[1], sys.argv[2]
    parts = []
    with tempfile.TemporaryDirectory() as workdir:
        for name, body in groups(src):
            want = sum(1 for line in body if is_instruction(line))
            halfwords, got = assemble(workdir, name, body)
            if got != want:
                sys.exit(f"{name}: {want} source instructions but {got} disassembled")
            const = "PROG_" + name
            parts.append(f"/// `{name}`: {want} instructions, {len(halfwords)} halfwords.")
            parts.append(f"pub const {const}: &[u16] = &[")
            row = []
            for h in halfwords:
                row.append(f"0x{h:04x},")
                if len(row) == 8:
                    parts.append("    " + " ".join(row))
                    row = []
            if row:
                parts.append("    " + " ".join(row))
            parts.append("];")
            parts.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tests/data/gen_thumb.py from tests/data/thumb_groups.s. Do not edit.\n\n")
        f.write("\n".join(parts))
        f.write("\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
