fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<PathBuf> = rd.flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            collect(&p, out);
        } else if matches!(
            p.extension().and_then(|x| x.to_str()),
            Some("v" | "sv" | "vh" | "svh")
        ) {
            out.push(p);
        }
    }
}

/// Include directories a design's files are compiled with: the file's own
/// directory and the usual subdirectories of its design.
fn include_dirs(root: &Path, file: &Path) -> Vec<PathBuf> {
    let mut dirs = vec![file.parent().expect("parent").to_path_buf()];
    let rel = file.strip_prefix(root).expect("under root");
    let comps: Vec<String> = rel
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect();
    if comps.len() > 3 && comps[0] == "tests" && comps[1] == "rtl" {
        let design = root.join("tests").join("rtl").join(&comps[2]);
        for sub in ["include", "rtl", "tb"] {
            dirs.push(design.join(sub));
        }
    }
    dirs
}

fn rel_name(root: &Path, p: &Path) -> String {
    p.strip_prefix(root)
        .expect("under root")
        .to_string_lossy()
        .replace('\\', "/")
}

/// The actual results: file -> the constructs it names.
fn actual_results() -> (usize, BTreeMap<String, BTreeSet<String>>) {
    let root = repo_root();
    let mut files = Vec::new();
    for sub in ["fixtures", "examples", "tests"] {
        collect(&root.join(sub), &mut files);
    }
    let mut results = BTreeMap::new();
    for f in &files {
        let opts = Options {
            include_dirs: include_dirs(&root, f),
            ..Options::default()
        };
        let parsed = parse_files(std::slice::from_ref(f), &opts);
        if !parsed.diagnostics.is_empty() {
            let constructs: BTreeSet<String> = parsed
                .diagnostics
                .iter()
                .map(|d| d.construct.clone())
                .collect();
            results.insert(rel_name(&root, f), constructs);
        }
    }
    (files.len(), results)
}

fn expected_results() -> BTreeMap<String, BTreeSet<String>> {
    let mut out = BTreeMap::new();
    for line in EXPECTED.lines().filter(|l| !l.trim().is_empty()) {
        let (file, constructs) = line.split_once('\t').expect("tab-separated line");
        out.insert(
            file.to_string(),
            constructs
                .split(", ")
                .map(str::to_string)
                .collect::<BTreeSet<String>>(),
        );
    }
    out
}

#[test]
fn corpus_files_match_the_pinned_parse_results() {
    let (total, actual) = actual_results();
    if std::env::var_os("RTL_CORPUS_PRINT").is_some() {
        for (file, cons) in &actual {
            let list: Vec<&str> = cons.iter().map(String::as_str).collect();
            println!("{file}\t{}", list.join(", "));
        }
    }
    assert!(total >= 140, "the corpus walk found only {total} files");
    let expected = expected_results();
    let mut problems = Vec::new();
    for (file, cons) in &actual {
        match expected.get(file) {
            None => problems.push(format!("NEW diagnostics in {file}: {cons:?}")),
            Some(e) if e != cons => {
                problems.push(format!("CHANGED {file}: expected {e:?}, got {cons:?}"))
            }
            _ => {}
        }
    }
    for file in expected.keys() {
        if !actual.contains_key(file) {
            problems.push(format!("CLEAN NOW (remove from EXPECTED): {file}"));
        }
    }
    assert!(
        problems.is_empty(),
        "{} corpus changes:\n{}",
        problems.len(),
        problems.join("\n")
    );
    println!(
        "corpus: {total} files, {} parse clean, {} with diagnostics",
        total - actual.len(),
        actual.len()
    );
}
